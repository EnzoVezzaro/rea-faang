      console.log(`Description: ${info.description || "—"}`);
      console.log(`Orchestrator: ${info.orchestrator || "—"}`);
      console.log(`Agents: ${info.agents?.length || 0}`);
      console.log(`Tools: ${info.tools?.join(", ") || "—"}`);
      console.log(`Runtime: ${info.runtime || "—"}`);
      console.log(`Repository: ${info.repository || "—"}`);
      console.log(`Dependencies: ${info.dependencies?.join(", ") || "—"}`);
      return;
