async function cmdInstall(args) {
  const pkg = await loadLib("pkg.mjs");
  const reg = await loadLib("registry.mjs");

  const target = process.cwd();

  if (!args.length) {
    // Install from local registry
    if (!reg) {
      console.log("install: registry not available yet (lib/registry.mjs not found)");
      return;
    }
    const lock = pkg ? pkg.readLockfile(target) : null;
    if (!lock || !Object.keys(lock.packages || {}).length) {
      console.log("install: no packages in lockfile — nothing to install");
      return;
    }
    console.log(`Installing ${Object.keys(lock.packages).length} package(s) from lockfile...`);
    for (const [name, info] of Object.entries(lock.packages)) {
      console.log(`  ${name}@${info.version} — already resolved`);
    }
    console.log("Done.");
    return;
  }

  // Git ref install
  const ref = args[0];
  if (!ref.startsWith("github:") && !ref.startsWith("git+https://")) {
    console.log(`install: unsupported ref "${ref}" — use github:user/repo[#ref] or git+https://...`);
    return;
  }
  if (!reg) {
    console.log("install: registry not available yet (lib/registry.mjs not found)");
    return;
  }
  const result = reg.installGit(ref);
  console.log(`Installed ${result.dir} @ ${result.version}`);
}

